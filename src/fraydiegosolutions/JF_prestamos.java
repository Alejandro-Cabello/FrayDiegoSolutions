    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        try {
            Conexion.buscarISBN = false;
            String buscar = Busqueda.getText();
            if (buscar.isEmpty()) {
                JOptionPane.showMessageDialog(null, "El campo está vacio", "Error", JOptionPane.ERROR_MESSAGE);
            } else {
                String strSql = "Select consultas.Id_libro, consultas.ISBN, consultas.Nombre, consultas.Publicacion, consultas.Editorial, consultas.Autor, consultas.Estante, consultas.Edicion, consultas.Unidades, consultas.Disponibilidad from consultas where ISBN like '%" + buscar + "%' or Nombre like '" + buscar + "%' or Publicacion like '" + buscar + "%' or Genero like '" + buscar + "%' or Editorial like '" + buscar + "%' or Autor like '" + buscar + "%' or Pais like '" + buscar + "%'";
                Conexion.conectar();
                Conexion.sentencia = Conexion.conn.prepareStatement(strSql);
                ResultSet objRes = Conexion.sentencia.executeQuery(strSql);
                System.out.println("Consulta Mostrar con exito");

                DefaultTableModel modelo = (DefaultTableModel) LibrosT.getModel();

                modelo.setRowCount(0);

                Object[] fila = new Object[10];
                while (objRes.next()) {
                    for (int i = 0; i < 10; i++) {
                        fila[i] = objRes.getObject(i + 1);

                    }
                    modelo.addRow(fila);
                    LibrosT.setModel(modelo);
                }

            }

        } catch (SQLException ex) {
            System.out.println(ex);
            JOptionPane.showMessageDialog(null, "Libro no encontrado, corriga su busqueda o ingrese un nuevo valor", "No encontrado", JOptionPane.DEFAULT_OPTION);

        }
    }//GEN-LAST:event_jButton1ActionPerformed

