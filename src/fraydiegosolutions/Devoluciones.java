    private void BuscarID1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BuscarID1ActionPerformed
        // TODO add your handling code here:

        try {
            Conexion.buscarlector = false;
            String buscar = getId.getText();
            if (buscar.isEmpty()) {
                JOptionPane.showMessageDialog(null, "El campo está vacio", "Error", JOptionPane.ERROR_MESSAGE);
            } else {
                String strSql = "Select prestamo.ID_usuario, prestamo.ID_libro, prestamo.ISBN, prestamo.Fecha_inicio, prestamo.Fecha_limite, prestamo.devolucion from prestamo where ID_usuario = '" + buscar + "'";
                Conexion.conectar();
                Conexion.sentencia = Conexion.conn.prepareStatement(strSql);
                ResultSet objRes = Conexion.sentencia.executeQuery(strSql);
                System.out.println("Consulta Mostrar con exito");

                DefaultTableModel modelo = (DefaultTableModel) TUsuario.getModel();

                modelo.setRowCount(0);

                Object[] fila = new Object[5];
                while (objRes.next()) {
                    for (int i = 0; i < 5; i++) {
                        fila[i] = objRes.getObject(i + 1);

                    }
                    modelo.addRow(fila);
                    TUsuario.setModel(modelo);
                }

            }

        } catch (SQLException ex) {
            System.out.println(ex);
            JOptionPane.showMessageDialog(null, "Libro no encontrado, corriga su busqueda o ingrese un nuevo valor", "No encontrado", JOptionPane.DEFAULT_OPTION);

        }

    }//GEN-LAST:event_BuscarID1ActionPerformed

