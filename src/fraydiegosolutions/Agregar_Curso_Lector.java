    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        
        
       try{
                 
         String ID_Lector = this.jTextFieldbuscar.getText();
         Cursos lector = Cursos.cargarLectorAl(ID_Lector);
         if (Conexion.buscarlector){
             this.id_lectorAl.setText(String.valueOf(lector.getID_Lector()));
             this.jTextFieldApellidop.setText(lector.getApellido_Paterno_Lector());
             this.jTextFieldApellidom.setText(lector.getApellido_Materno_Lector());
             this.jTextFieldnom.setText(lector.getNombre_Lector());
             this.jTextFieldedad.setText(lector.getEdad_Lector());
             this.jTextFieldedad.setText(lector.getTelefono_Lector());
         }
         else{
             JOptionPane.showMessageDialog(this, "cliente no existe", "Buscar", 2);
         }
     }catch(Exception e){
         
     }  
        
        
        
        
    }//GEN-LAST:event_jButton1ActionPerformed

    private void BotonAgregarLectorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BotonAgregarLectorActionPerformed
       
        try {
            PreparedStatement pps = conn.prepareStatement("INSERT INTO lector_curso (ID_Lector, Escuela, Curso) VALUES(?,?,?)");
            pps.setString(1,id_lectorAl.getText());         
            pps.setString(2, (String) agregar_escuela.getSelectedItem());
            pps.setString(3, (String) agregar_curso.getSelectedItem());
            pps.executeUpdate();
            JOptionPane.showMessageDialog(null, "Datos Guardados");
        } catch (SQLException ex) {
            java.util.logging.Logger.getLogger(Agregar_Curso_Lector.class.getName()).log(Level.SEVERE, null, ex);
        }

       
    }//GEN-LAST:event_BotonAgregarLectorActionPerformed

